/**
 * `bun run build` in design/: bundles src/*.css (fonts, tokens, base, prose, reader, workspace,
 * concept, comments, views, inbox, public, in that order) into dist/tempra.css for the site, and
 * dist/tempra.ts for the app's Worker, which serves it at a content-hashed URL with the fonts
 * (design/fonts/*.woff2) beside it, each at its own content-hashed URL. Both outputs are committed;
 * design.test.ts fails when they are stale.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = import.meta.dir;
export const SOURCES = [
  "fonts.css",
  "tokens.css",
  "base.css",
  "prose.css",
  "reader.css",
  "workspace.css",
  "concept.css",
  "comments.css",
  "views.css",
  "inbox.css",
  "public.css",
];

const sha = (data: string | Uint8Array) =>
  new Bun.CryptoHasher("sha256").update(data).digest("hex").slice(0, 12);

export function generate(): { css: string; ts: string } {
  // The site's stylesheet: fonts by their path in the package, which its bundler resolves.
  const css = `${SOURCES.map((f) => readFileSync(join(ROOT, "src", f), "utf8").trim()).join("\n\n")}\n`;
  // The app's: each font at /_design/<name>.<hash>.woff2, so it can be cached for good.
  const fonts: Record<string, string> = {};
  let appCss = css;
  for (const file of readdirSync(join(ROOT, "fonts"))
    .filter((f) => f.endsWith(".woff2"))
    .sort()) {
    const bytes = readFileSync(join(ROOT, "fonts", file));
    const served = file.replace(/\.woff2$/, `.${sha(bytes)}.woff2`);
    fonts[served] = bytes.toString("base64");
    appCss = appCss.replaceAll(`url("../fonts/${file}")`, `url("/_design/${served}")`);
  }
  const hash = sha(appCss);
  const ts = `// Generated by design/build.ts from design/src/*.css and design/fonts/; edit those and run \`bun run build\`.

/** The whole stylesheet: fonts, tokens, base and prose. */
export const css: string = ${JSON.stringify(appCss)};

/** First 12 hex characters of the stylesheet's SHA-256, for an immutable URL. */
export const hash = ${JSON.stringify(hash)};

/** Where the app serves it. */
export const href = \`/_design/tempra.\${hash}.css\`;

/** The fonts the stylesheet names, by the file name it asks for under /_design/, as base64. */
export const fonts: Record<string, string> = ${JSON.stringify(fonts)};
`;
  return { css, ts };
}

if (import.meta.main) {
  const { css, ts } = generate();
  writeFileSync(join(ROOT, "dist", "tempra.css"), css);
  writeFileSync(join(ROOT, "dist", "tempra.ts"), ts);
  console.log("Wrote dist/tempra.css and dist/tempra.ts");
}
