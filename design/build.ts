/**
 * `bun run build` in design/: bundles src/*.css (tokens, base, prose, reader, workspace, concept,
 * comments, views, inbox, public, in that order) into dist/tempra.css for the site, and dist/tempra.ts
 * for the app's Worker, which serves it at a content-hashed URL. Both outputs are committed;
 * design.test.ts fails when they are stale.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = import.meta.dir;
export const SOURCES = [
  "tokens.css",
  "base.css",
  "prose.css",
  "reader.css",
  "workspace.css",
  "concept.css",
  "comments.css",
  "views.css",
  "inbox.css",
  "public.css",
];

export function generate(): { css: string; ts: string } {
  const css = `${SOURCES.map((f) => readFileSync(join(ROOT, "src", f), "utf8").trim()).join("\n\n")}\n`;
  const hash = new Bun.CryptoHasher("sha256").update(css).digest("hex").slice(0, 12);
  const ts = `// Generated by design/build.ts from design/src/*.css; edit those and run \`bun run build\`.

/** The whole stylesheet: tokens, base and prose. */
export const css: string = ${JSON.stringify(css)};

/** First 12 hex characters of the stylesheet's SHA-256, for an immutable URL. */
export const hash = ${JSON.stringify(hash)};

/** Where the app serves it. */
export const href = \`/_design/tempra.\${hash}.css\`;
`;
  return { css, ts };
}

if (import.meta.main) {
  const { css, ts } = generate();
  writeFileSync(join(ROOT, "dist", "tempra.css"), css);
  writeFileSync(join(ROOT, "dist", "tempra.ts"), ts);
  console.log("Wrote dist/tempra.css and dist/tempra.ts");
}
