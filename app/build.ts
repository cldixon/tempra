/**
 * `bun run build` in app/ (also run by `bun install`): bundles src/main.tsx with Vite into one
 * ES module and writes dist/app.ts, which exports it as `js` with its `hash` and `href`, for the
 * Worker to serve at a content-hashed URL (as it serves @tempra/design). dist/ is not committed.
 * `--watch` rebuilds on every change, for `bun run dev` beside the Worker's `cf dev`.
 */
import { mkdirSync, watch as watchFiles, writeFileSync } from "node:fs";
import { join } from "node:path";
import { build, type Rollup } from "vite";

const ROOT = import.meta.dir;
const watch = process.argv.includes("--watch");

export function moduleSource(js: string): string {
  const hash = new Bun.CryptoHasher("sha256").update(js).digest("hex").slice(0, 12);
  return `// Generated by app/build.ts from app/src; run \`bun run build\` in app/.

/** The app's whole client bundle, one ES module. */
export const js: string = ${JSON.stringify(js)};

/** First 12 hex characters of the bundle's SHA-256, for an immutable URL. */
export const hash = ${JSON.stringify(hash)};

/** Where the Worker serves it. */
export const href = \`/_app/app.\${hash}.js\`;
`;
}

/** Builds once and writes dist/app.ts. */
export async function buildApp(): Promise<void> {
  const result = (await build({
    root: ROOT,
    configFile: false,
    logLevel: "warn",
    mode: "production",
    define: { "process.env.NODE_ENV": JSON.stringify("production") },
    build: {
      write: false,
      target: "es2022",
      minify: true,
      sourcemap: false,
      modulePreload: false,
      rollupOptions: {
        input: join(ROOT, "src/main.tsx"),
        output: { format: "es", codeSplitting: false },
      },
    },
  })) as Rollup.RollupOutput | Rollup.RollupOutput[];
  const output = Array.isArray(result) ? result[0] : result;
  const chunk = output?.output.find((o): o is Rollup.OutputChunk => o.type === "chunk");
  if (!chunk) throw new Error("Vite produced no JavaScript.");
  mkdirSync(join(ROOT, "dist"), { recursive: true });
  writeFileSync(join(ROOT, "dist", "app.ts"), moduleSource(chunk.code));
  console.log(`app: wrote dist/app.ts (${(chunk.code.length / 1024).toFixed(0)} KB)`);
}

if (import.meta.main) {
  await buildApp();
  if (watch) {
    let timer: ReturnType<typeof setTimeout> | undefined;
    watchFiles(join(ROOT, "src"), { recursive: true }, () => {
      clearTimeout(timer);
      timer = setTimeout(() => buildApp().catch((e) => console.error(e)), 100);
    });
    console.log("app: watching src/");
  }
}
