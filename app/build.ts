/**
 * `bun run build` in app/ (also run by `bun install`): bundles src/main.tsx with Vite into an ES
 * module entry and the chunks it imports on demand (Pele, for pages with a diagram), and writes
 * dist/app.ts, which exports the entry as `js` with its `hash` and `href`, and the chunks by file
 * name, for the Worker to serve at content-hashed URLs beside it under /_app/ (as it serves
 * @tempra/design). dist/ is not committed.
 * `--watch` rebuilds on every change, for `bun run dev` beside the Worker's `cf dev`.
 */
import { mkdirSync, watch as watchFiles, writeFileSync } from "node:fs";
import { join } from "node:path";
import { build, type Rollup } from "vite";

const ROOT = import.meta.dir;
const watch = process.argv.includes("--watch");

/**
 * dist/app.ts for an entry and its chunks. `hash` is the one in the entry's file name (Vite's
 * content hash, which the chunks import it by), or for a bare `js` the first 12 hex characters of
 * its SHA-256.
 */
export function moduleSource(js: string, chunks: Record<string, string> = {}, file?: string) {
  const hash =
    (file && /^app\.([\w-]+)\.js$/.exec(file)?.[1]) ||
    new Bun.CryptoHasher("sha256").update(js).digest("hex").slice(0, 12);
  return `// Generated by app/build.ts from app/src; run \`bun run build\` in app/.

/** The app's client bundle: the entry, one ES module. */
export const js: string = ${JSON.stringify(js)};

/** The entry's content hash, for an immutable URL. */
export const hash = ${JSON.stringify(hash)};

/** Where the Worker serves it (the name its chunks import it by). */
export const href = \`/_app/app.\${hash}.js\`;

/**
 * What the entry imports on demand, by file name (\`<name>-<hash>.js\`, so immutable), served at
 * /_app/<file>.
 */
export const chunks: Record<string, string> = ${JSON.stringify(chunks)};
`;
}

/** Builds once and writes dist/app.ts. */
export async function buildApp(): Promise<void> {
  const result = (await build({
    root: ROOT,
    configFile: false,
    logLevel: "warn",
    mode: "production",
    define: { "process.env.NODE_ENV": JSON.stringify("production") },
    build: {
      write: false,
      target: "es2022",
      minify: true,
      sourcemap: false,
      modulePreload: false,
      rollupOptions: {
        input: join(ROOT, "src/main.tsx"),
        output: {
          format: "es",
          entryFileNames: "app.[hash].js",
          chunkFileNames: "[name]-[hash].js",
        },
      },
    },
  })) as Rollup.RollupOutput | Rollup.RollupOutput[];
  const output = Array.isArray(result) ? result[0] : result;
  const all = output?.output.filter((o): o is Rollup.OutputChunk => o.type === "chunk") ?? [];
  const entry = all.find((c) => c.isEntry);
  if (!entry) throw new Error("Vite produced no JavaScript.");
  const chunks = Object.fromEntries(all.filter((c) => !c.isEntry).map((c) => [c.fileName, c.code]));
  mkdirSync(join(ROOT, "dist"), { recursive: true });
  writeFileSync(join(ROOT, "dist", "app.ts"), moduleSource(entry.code, chunks, entry.fileName));
  const lazy = Object.values(chunks).reduce((n, c) => n + c.length, 0);
  console.log(
    `app: wrote dist/app.ts (${(entry.code.length / 1024).toFixed(0)} KB, and ${Object.keys(chunks).length} chunks on demand, ${(lazy / 1024).toFixed(0)} KB)`,
  );
}

if (import.meta.main) {
  await buildApp();
  if (watch) {
    let timer: ReturnType<typeof setTimeout> | undefined;
    watchFiles(join(ROOT, "src"), { recursive: true }, () => {
      clearTimeout(timer);
      timer = setTimeout(() => buildApp().catch((e) => console.error(e)), 100);
    });
    console.log("app: watching src/");
  }
}
